/**
 * Writes lib/destination-map.generated.ts — a static id -> slug table.
 *
 * The /destinations/trip?destination=<id> redirect only needs to turn an id
 * into a slug. Doing that from the database costs an Aiven connection, which
 * on a cold serverless invocation measured 2.3s for a response whose entire
 * body is a Location header. This table makes it pure CPU.
 *
 * Runs as part of `npm run build`, so it cannot drift from the database. If
 * the database is unreachable at build time the existing file is kept rather
 * than emptied — a stale entry still redirects correctly, and the route falls
 * back to a database lookup for any id the table does not cover.
 */
import { writeFile, access } from "node:fs/promises"
import { PrismaClient } from "@prisma/client"
import { PrismaPg } from "@prisma/adapter-pg"
import { Pool } from "pg"

const OUT = new URL("../lib/destination-map.generated.ts", import.meta.url)

function destinationSlug(name) {
    return name
        .toLowerCase()
        .replace(/,.*$/, "")
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "")
}

async function keepExisting(reason) {
    try {
        await access(OUT)
        console.warn(`destination map: ${reason} — keeping the existing file`)
        process.exit(0)
    } catch {
        console.warn(`destination map: ${reason} — writing an empty table`)
        await writeFile(OUT, render([]), "utf8")
        process.exit(0)
    }
}

function render(rows) {
    const entries = rows.map(([id, slug]) => `    ${id}: ${JSON.stringify(slug)},`).join("\n")
    return `// Generated by scripts/generate-destination-map.mjs — do not edit.
// Regenerated on every build; see that script for why this exists.

export const DESTINATION_SLUG_BY_ID: Record<number, string> = {
${entries}
}
`
}

const connectionString = process.env.DATABASE_URL
if (!connectionString) await keepExisting("DATABASE_URL is not set")

// Aiven presents a self-signed chain, as lib/prisma.ts does for dev.
process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0"
const pool = new Pool({ connectionString, ssl: { rejectUnauthorized: false }, max: 1 })
const prisma = new PrismaClient({ adapter: new PrismaPg(pool) })

try {
    const rows = await prisma.destination.findMany({
        select: { id: true, name: true },
        orderBy: { id: "asc" },
    })
    await writeFile(OUT, render(rows.map((d) => [d.id, destinationSlug(d.name)])), "utf8")
    console.log(`destination map: wrote ${rows.length} entries`)
} catch (error) {
    await keepExisting(error?.message || String(error))
} finally {
    await prisma.$disconnect().catch(() => {})
    await pool.end().catch(() => {})
}
